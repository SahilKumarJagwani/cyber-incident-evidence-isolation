#!/usr/bin/env python3
"""
Evidence intake service -- runs INSIDE the Ubuntu sandbox VM, with no network.

Evidence arrives over the VM's COM1 serial port (/dev/ttyS0), which
VirtualBox connects to a named pipe on the Windows host. Evidence is written
to a quarantine "vault" directory and is never opened, parsed, or executed.

Operations (each request is an HMAC-authenticated frame):
  ping                      connectivity check
  store   <id>              save an upload into the vault
  release <id>              re-verify the hash, move to the analysis folder
  delete  <id>              remove a vault file (used for rollbacks)

<id> is a 32-character lowercase hex string generated by the Windows app.
Only the standard library is used.

Configuration (environment variables):
  RECEIVER_TOKEN     shared secret, at least 32 characters (required)
  RECEIVER_DEVICE    default /dev/ttyS0
  RECEIVER_VAULT     default /srv/evidence/incoming
  RECEIVER_ANALYSIS  default /srv/evidence/analysis
  RECEIVER_IDLE      seconds of silence mid-frame before giving up (default 10)
"""

import hashlib
import hmac
import json
import os
import re
import select
import struct
import sys
import time
import traceback

DEVICE = os.environ.get("RECEIVER_DEVICE", "/dev/ttyS0")
TOKEN = os.environ.get("RECEIVER_TOKEN", "")
VAULT = os.environ.get("RECEIVER_VAULT", "/srv/evidence/incoming")
ANALYSIS = os.environ.get("RECEIVER_ANALYSIS", "/srv/evidence/analysis")
IDLE = float(os.environ.get("RECEIVER_IDLE", "10"))

MAGIC = b"EVD1"
MAX_HEADER = 8192
MAX_BYTES = 5 * 1024 * 1024
MAX_BODY = MAX_BYTES + 1024
MAC_LEN = 32
ALLOWED_EXTENSIONS = {"png", "jpg", "jpeg", "pdf", "txt", "eml"}

ID_RE = re.compile(r"^[0-9a-f]{32}$")
SHA_RE = re.compile(r"^[0-9a-f]{64}$")


def log(message):
    sys.stderr.write("%s\n" % message)
    sys.stderr.flush()


# framing

def _mac(key, lengths, header, body):
    digest = hmac.new(key, digestmod=hashlib.sha256)
    digest.update(lengths)
    digest.update(header)
    digest.update(body)
    return digest.digest()


def encode_frame(key, header_dict, body=b""):
    header = json.dumps(header_dict, separators=(",", ":")).encode("utf-8")
    lengths = struct.pack(">II", len(header), len(body))
    return MAGIC + lengths + header + body + _mac(key, lengths, header, body)


class SerialPort:
    def __init__(self, path):
        import termios
        import tty

        self.fd = os.open(path, os.O_RDWR | os.O_NOCTTY)
        tty.setraw(self.fd)

        attrs = termios.tcgetattr(self.fd)
        attrs[2] |= termios.CLOCAL | termios.CREAD       # ignore modem lines
        attrs[2] &= ~getattr(termios, "CRTSCTS", 0)      # no hardware flow ctl
        attrs[4] = attrs[5] = termios.B115200
        attrs[6][termios.VMIN] = 1
        attrs[6][termios.VTIME] = 0
        termios.tcsetattr(self.fd, termios.TCSANOW, attrs)
        termios.tcflush(self.fd, termios.TCIOFLUSH)

    def read(self, count, idle=None):
        if idle is not None:
            ready, _, _ = select.select([self.fd], [], [], idle)
            if not ready:
                raise TimeoutError("idle")
        return os.read(self.fd, count)

    def write(self, data):
        view = memoryview(data)
        while len(view):
            written = os.write(self.fd, view[:4096])
            view = view[written:]

    def close(self):
        try:
            os.close(self.fd)
        except OSError:
            pass


class Reader:
    def __init__(self, port):
        self.port = port
        self.buf = bytearray()

    def _fill(self, idle=None):
        data = self.port.read(65536, idle)
        if not data:
            raise EOFError("serial port closed")
        self.buf += data

    def need(self, count, idle=None):
        while len(self.buf) < count:
            self._fill(idle)

    def find_magic(self):
        while True:
            index = self.buf.find(MAGIC)
            if index >= 0:
                del self.buf[:index + len(MAGIC)]
                return
            del self.buf[:max(0, len(self.buf) - (len(MAGIC) - 1))]
            self._fill()


def read_frame(reader, key, idle=None):
    """Return (header_dict, body) of the next valid frame."""

    while True:
        reader.find_magic()
        try:
            reader.need(8, idle)
            header_len, body_len = struct.unpack(">II", bytes(reader.buf[:8]))
            if not (0 < header_len <= MAX_HEADER) or body_len > MAX_BODY:
                continue
            total = 8 + header_len + body_len + MAC_LEN
            reader.need(total, idle)
        except TimeoutError:
            if idle is None:
                raise
            # Sender went quiet mid-frame: drop it and rescan what we have.
            continue

        lengths = bytes(reader.buf[:8])
        header = bytes(reader.buf[8:8 + header_len])
        body = bytes(reader.buf[8 + header_len:8 + header_len + body_len])
        mac = bytes(reader.buf[8 + header_len + body_len:total])

        if hmac.compare_digest(mac, _mac(key, lengths, header, body)):
            try:
                parsed = json.loads(header)
            except ValueError:
                continue
            if isinstance(parsed, dict):
                del reader.buf[:total]
                return parsed, body

        log("discarded a frame that failed authentication")


# operations

def safe_display_name(raw_name):
    """Sanitised name for the analysis folder. Never used to build vault paths."""
    base = os.path.basename(str(raw_name).replace("\\", "/"))
    base = re.sub(r"[^A-Za-z0-9._-]", "_", base)[:100] or "evidence"
    extension = base.rsplit(".", 1)[-1].lower() if "." in base else ""
    if extension not in ALLOWED_EXTENSIONS:
        base += ".bin"
    return base


def sha256_of_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(65536), b""):
            digest.update(block)
    return digest.hexdigest()


def do_store(evidence_id, header, body):
    claimed = str(header.get("sha256", "")).lower()
    if not SHA_RE.match(claimed):
        return 400, {"error": "sha256 required"}
    if len(body) == 0 or len(body) > MAX_BYTES:
        return 413, {"error": "bad size"}

    actual = hashlib.sha256(body).hexdigest()
    if actual != claimed:
        return 422, {"error": "hash mismatch", "sha256": actual}

    final_path = os.path.join(VAULT, evidence_id + ".bin")
    part_path = final_path + ".part"
    meta_path = os.path.join(VAULT, evidence_id + ".json")

    if os.path.exists(final_path):
        return 409, {"error": "id already exists"}

    try:
        # O_EXCL: never overwrite; 0600: readable only by this service user.
        fd = os.open(part_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "wb") as out:
            out.write(body)
        os.rename(part_path, final_path)
    except OSError as error:
        if os.path.exists(part_path):
            os.remove(part_path)
        return 500, {"error": "could not store: %s" % error}

    with open(meta_path, "w", encoding="utf-8") as meta:
        json.dump({
            "original_name": str(header.get("name", "evidence"))[:255],
            "sha256": actual,
            "size": len(body),
            "received_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "released_as": None,
        }, meta)
    os.chmod(meta_path, 0o600)

    return 201, {"sha256": actual, "size": len(body)}


def do_release(evidence_id, header):
    expected = str(header.get("sha256", "")).lower()
    if not SHA_RE.match(expected):
        return 400, {"error": "sha256 required"}

    vault_path = os.path.join(VAULT, evidence_id + ".bin")
    meta_path = os.path.join(VAULT, evidence_id + ".json")
    if not os.path.isfile(meta_path):
        return 404, {"error": "unknown evidence id"}

    with open(meta_path, encoding="utf-8") as meta:
        info = json.load(meta)

    if info.get("released_as"):
        return 200, {"status": "already_released", "path": info["released_as"]}
    if not os.path.isfile(vault_path):
        return 404, {"error": "vault file missing"}

    actual = sha256_of_file(vault_path)
    if actual != expected or actual != info.get("sha256"):
        return 409, {"error": "integrity check failed"}

    target_name = "%s_%s" % (evidence_id[:8], safe_display_name(info["original_name"]))
    target_path = os.path.join(ANALYSIS, target_name)
    os.replace(vault_path, target_path)
    os.chmod(target_path, 0o444)          # read-only for the analyst

    info["released_as"] = target_path
    with open(meta_path, "w", encoding="utf-8") as meta:
        json.dump(info, meta)

    return 200, {"status": "released", "path": target_path}


def do_delete(evidence_id):
    for suffix in (".bin", ".bin.part", ".json"):
        path = os.path.join(VAULT, evidence_id + suffix)
        if os.path.isfile(path):
            os.remove(path)
    return 200, {"status": "deleted"}


def handle(header, body):
    operation = header.get("op")
    if operation == "ping":
        return 200, {"status": "ok"}

    evidence_id = header.get("id", "")
    if not isinstance(evidence_id, str) or not ID_RE.match(evidence_id):
        return 400, {"error": "bad id"}

    if operation == "store":
        return do_store(evidence_id, header, body)
    if operation == "release":
        return do_release(evidence_id, header)
    if operation == "delete":
        return do_delete(evidence_id)
    return 400, {"error": "unknown op"}


# main

def serve(key):
    port = SerialPort(DEVICE)
    reader = Reader(port)
    log("Evidence receiver listening on %s" % DEVICE)

    while True:
        try:
            header, body = read_frame(reader, key, idle=IDLE)
        except (OSError, EOFError) as error:
            log("serial error (%s); reopening in 1s" % error)
            port.close()
            time.sleep(1)
            try:
                port = SerialPort(DEVICE)
                reader = Reader(port)
            except OSError as open_error:
                log("could not reopen %s: %s" % (DEVICE, open_error))
            continue

        try:
            code, payload = handle(header, body)
        except Exception:
            log(traceback.format_exc())
            code, payload = 500, {"error": "internal error"}

        reply = dict(payload, nonce=header.get("nonce"), code=code)
        try:
            port.write(encode_frame(key, reply))
        except OSError as error:
            log("could not send reply: %s" % error)


def main():
    if len(TOKEN) < 32:
        raise SystemExit("Set RECEIVER_TOKEN to a secret of at least 32 characters.")
    os.makedirs(VAULT, mode=0o700, exist_ok=True)
    os.makedirs(ANALYSIS, mode=0o750, exist_ok=True)
    serve(TOKEN.encode("utf-8"))


if __name__ == "__main__":
    main()